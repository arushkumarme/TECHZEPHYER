"""Render the vocabulary registry as the docs/05 appendix and a JSON export (conformance kit).

Both outputs are pure functions of the TOML files, so ``scripts/generate_docs.py`` is
idempotent and a test can detect a stale appendix or export.
"""

from __future__ import annotations

import json
from typing import Any

from netcoop.core.vocabulary.registry import all_vocabularies

APPENDIX_BEGIN = "<!-- BEGIN GENERATED: vocabulary -->"
APPENDIX_END = "<!-- END GENERATED: vocabulary -->"


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_appendix() -> str:
    vocabs = all_vocabularies()
    lines = [
        APPENDIX_BEGIN,
        "",
        "_Generated by `scripts/generate_docs.py` from `config/vocabulary/*.toml`; do not edit "
        "by hand. A term marked **blocked** is defined but always rejected._",
        "",
        "| Vocabulary | Terms | Closed? | Enforced in code by |",
        "|---|---|---|---|",
    ]
    for v in vocabs.values():
        lines.append(
            f"| [`{v.name}`](#vocabulary-{v.name.replace('_', '-')}) | {len(v.terms)} | "
            f"{'extensible (`x-` ids)' if v.extensible else 'closed'} | "
            f"{'`' + v.code_literal + '`' if v.code_literal else 'registry only'} |"
        )
    for v in vocabs.values():
        lines += [
            "",
            f"### Vocabulary: {v.name}",
            "",
            _cell(v.description),
            "",
            "| Id | Label | Definition | Status | Source | Attributes |",
            "|---|---|---|---|---|---|",
        ]
        for t in v.terms:
            attrs = ", ".join(f"{k}={_attr(val)}" for k, val in t.attributes.items())
            status = f"**{t.status}**" if t.status == "blocked" else t.status
            lines.append(
                f"| `{t.id}` | {_cell(t.label)} | {_cell(t.definition)} | {status} | "
                f"{_cell(t.source)} | {_cell(attrs)} |"
            )
    lines += ["", APPENDIX_END]
    return "\n".join(lines)


def _attr(value: Any) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(str(v) for v in value) + "]"
    return str(value)


def render_json() -> str:
    data = {
        name: {
            "version": v.version,
            "extensible": v.extensible,
            "description": v.description,
            "terms": [t.model_dump(exclude={"unrecognised"}) for t in v.terms],
        }
        for name, v in all_vocabularies().items()
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"
