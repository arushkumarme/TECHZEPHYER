"""Seeded runner for the organizer's synthetic telemetry generator.

The organizer's Colab notebook (``SRC-1 p4 §5``) is vendored *unchanged* under
``sample_data/generator/``. This module extracts the notebook's code cell, checks the
file's SHA-256 so a modified copy can never be run by mistake, and executes the
organizer's ``generate_telemetry`` with:

* a seeded ``random.Random`` instead of the global ``random`` module, and
* a fixed clock instead of ``datetime.utcnow()``,

so that scenario inputs can be regenerated byte-for-byte. The organizer code itself is
not altered; only the two module globals it reads are substituted.
"""

from __future__ import annotations

import contextlib
import hashlib
import io
import json
import random
import threading
import warnings
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_NOTEBOOK = REPO_ROOT / "sample_data" / "generator" / "organizer_generator.ipynb"
EXPECTED_SHA256 = "f245012f96a878a10653d14df95bdb45cbd6c59f42c8fe61d33efebf70aea460"

#: Fault profiles implemented by the organizer code (OBSERVED in the notebook's if/elif).
FAULT_TYPES: tuple[str, ...] = ("normal", "latency_spike", "hardware_failure")


class GeneratorIntegrityError(RuntimeError):
    """The notebook on disk is not the vendored organizer generator."""


def _fixed_clock(at: datetime) -> type:
    naive_utc = at.astimezone(UTC).replace(tzinfo=None)

    class _FixedDatetime:
        @staticmethod
        def utcnow() -> datetime:
            return naive_utc

    return _FixedDatetime


@dataclass
class GeneratorHandle:
    """A loaded organizer generator. Thread-safe."""

    source: str
    _fn: Callable[[str], dict[str, Any]]
    _globals: dict[str, Any]

    def __post_init__(self) -> None:
        self._lock = threading.Lock()

    def generate(self, fault_type: str, *, seed: int, at: datetime) -> dict[str, Any]:
        """Return one organizer record for ``fault_type`` with deterministic randomness."""
        if fault_type not in FAULT_TYPES:
            raise ValueError(f"unknown fault_type {fault_type!r}; expected one of {FAULT_TYPES}")
        if at.tzinfo is None:
            raise ValueError("'at' must be timezone-aware")
        with self._lock:
            self._globals["random"] = random.Random(seed)
            self._globals["datetime"] = _fixed_clock(at)
            record = self._fn(fault_type)
        # Round-trip through JSON: the organizer prints records as JSON, and this
        # guarantees the result is plain data.
        result: dict[str, Any] = json.loads(json.dumps(record))
        return result


def load_generator(path: Path = DEFAULT_NOTEBOOK) -> GeneratorHandle:
    """Load the vendored notebook, verifying its hash first."""
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise GeneratorIntegrityError(
            f"{path} has SHA-256 {digest}, expected {EXPECTED_SHA256} (vendored organizer copy)"
        )
    notebook = json.loads(raw)
    cells = [
        "".join(c["source"])
        for c in notebook["cells"]
        if c["cell_type"] == "code" and "def generate_telemetry" in "".join(c["source"])
    ]
    if len(cells) != 1:
        raise GeneratorIntegrityError("expected exactly one cell defining generate_telemetry")
    source = cells[0]
    namespace: dict[str, Any] = {"__name__": "organizer_generator"}
    # The cell ends with an example print and calls the deprecated utcnow(); silence both.
    with (
        contextlib.redirect_stdout(io.StringIO()),
        warnings.catch_warnings(),
    ):
        warnings.simplefilter("ignore", DeprecationWarning)
        exec(compile(source, str(path), "exec"), namespace)
    fn = namespace["generate_telemetry"]
    return GeneratorHandle(source=source, _fn=fn, _globals=namespace)
